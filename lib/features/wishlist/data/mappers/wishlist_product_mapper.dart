import '../../../../core/helpers/json_converter.dart';
import '../../domain/entities/wishlist_product_entity.dart';
import '../models/wishlist_product_model.dart';



class WishlistProductMapper {
  
  static WishlistProductModel fromJson(Map<String, dynamic> json) => WishlistProductModel(
      id: json['id']?.toString() ?? '',
      name: json['title']?.toString() ?? '',
      price: JsonConverter.parseDouble(json['price']),
      originalPrice: json['originalPrice'] != null ? JsonConverter.parseDouble(json['oldPrice'], 0) : null,
      unit: json['unit']?.toString(),
      subName: json['subTitle']?.toString() ?? '',
      tag: json['tag']?.toString() ?? '',
      slug: json['slug']?.toString() ?? '',
      thumbnail: json['thumbnail']?.toString() ?? '',
      discount: JsonConverter.parseDouble(json['discount'], 0),
      discountType: json['discountType']?.toString(),
      isFavorite: json['isFavorite'] as bool? ?? true,
      images: JsonConverter.parseList<String>(json['images'], (e) => e.toString()),
       nutritionLines: JsonConverter.parseNutrition(json['nutritionalInfo'] ?? json['nutritionLines']),
      rating: JsonConverter.parseRating(json),
     
      reviewCount: JsonConverter.parseInt(json['reviewCount']),
      brand: JsonConverter.parseBrand(json['brand']),
      shippingCost: JsonConverter.parseDouble(json['shippingCost'], 0),
      currentStock: JsonConverter.parseInt(json['currentStock']),
      categoryIds: JsonConverter.parseList<int>(json['categoryIds'], (e) => int.tryParse(e.toString()) ?? 0),
      minOrderQty: JsonConverter.parseInt(json['minOrderQty'], 1),
      status: JsonConverter.parseInt(json['status'], 1),
    );

  static WishlistProductModel toModel(WishlistProductEntity entity) => WishlistProductModel(
      id: entity.id,
      name: entity.name,
      price: entity.price,
      originalPrice: entity.originalPrice,
      unit: entity.unit,
      subName: entity.subName,
      tag: entity.tag,
      slug: entity.slug,
      thumbnail: entity.thumbnail,
      discount: entity.discount,
      discountType: entity.discountType,
      isFavorite: entity.isFavorite,
      images: entity.images,
      nutritionLines: entity.nutritionLines,
      rating: entity.rating,
      reviewCount: entity.reviewCount,
      brand: entity.brand,
      shippingCost: entity.shippingCost,
      currentStock: entity.currentStock,
      categoryIds: entity.categoryIds,
      minOrderQty: entity.minOrderQty,
      status: entity.status,
    );
  static WishlistProductEntity toEntity(WishlistProductModel model) => WishlistProductEntity(
      id: model.id,
      name: model.name,
      price: model.price,
      originalPrice: model.originalPrice,
      unit: model.unit,
      subName: model.subName,
      tag: model.tag,
      slug: model.slug,
      thumbnail: model.thumbnail,
      discount: model.discount,
      discountType: model.discountType,
      isFavorite: model.isFavorite,
      images: model.images,
      nutritionLines: model.nutritionLines,
      rating: model.rating,
      reviewCount: model.reviewCount,
      brand: model.brand,
      shippingCost: model.shippingCost,
      currentStock: model.currentStock,
      categoryIds: model.categoryIds,
      minOrderQty: model.minOrderQty,
      status: model.status,
    );
    
  static Map<String, dynamic> toJson(WishlistProductModel model) => {
      'id': model.id,
      'title': model.name,
      'price': model.price,
      'originalPrice': model.originalPrice,
      'unit': model.unit,
      'subTitle': model.subName,
      'tag': model.tag,
      'slug': model.slug,
      'thumbnail': model.thumbnail,
      'discount': model.discount,
      'discountType': model.discountType,
      'isFavorite': model.isFavorite,
      'images': model.images,
      'nutritionLines': model.nutritionLines,
      'rating': model.rating,
      'review_count': model.reviewCount,
      'brand': model.brand,
      'shippingCost': model.shippingCost,
      'wish_list_count': model.isFavorite ? 1 : 0,
      'current_stock': model.currentStock,
      'category_ids': model.categoryIds,
      'minimum_order_qty': model.minOrderQty,
      'status': model.status,
    };
}
